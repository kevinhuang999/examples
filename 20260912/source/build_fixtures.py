# -*- coding: utf-8 -*-
"""重造示例数据：跑一遍就能得到 01_raw_data/检验结果_仪器导出.csv。

上半部分：定列名，以及每个样品各自要检哪些项目（含故意造的边界值）。
下半部分：把这些数据按「仪器工作站导出」的样子写成 CSV——开头是通行的表头，
末尾留着空行、表尾合计行和一行说明，专门用来验证脚本会不会把垃圾行当成数据。

    python source/build_fixtures.py
"""
import csv
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent      # 本文件在 source/ 里，往上跳一层才是包根
RAW = BASE / "01_raw_data" / "检验结果_仪器导出.csv"

# ---------- 上半部分：列名与数据 ----------

HEAD = ["样品编号", "样品名称", "批号", "检验项目", "标准规定",
        "检验结果", "单位", "单项结论", "检测人", "检测日期"]

def _full_items() -> list:
    """全检样品的检项，凑到 34 条，一页装不下，必须跨页。"""
    items = [
        ("性状", "无色或几乎无色的澄明液体", "无色澄明液体", "—", "符合"),
        ("pH 值", "5.0~7.0", "6.1", "—", "符合"),
        ("透光率", "≥98.0%", "99.6", "%", "符合"),
        ("可见异物", "应符合规定", "符合", "—", "符合"),
        ("不溶性微粒", "≥10μm 不得过 6000 粒", "812", "粒", "符合"),
        ("细菌内毒素", "<0.5 EU/ml", "0.08", "EU/ml", "符合"),
        ("无菌", "应符合规定", "符合", "—", "符合"),
        ("含量-氨基酸总量", "95.0%~105.0%", "100.2", "%", "符合"),
        ("含量-亮氨酸", "90.0%~110.0%", "98.7", "%", "符合"),
        ("含量-苯丙氨酸", "90.0%~110.0%", "101.5", "%", "符合"),
        ("含量-谷氨酸", "90.0%~110.0%", "99.1", "%", "符合"),
        ("渗透压摩尔浓度", "260~320 mOsmol/kg", "291", "mOsmol/kg", "符合"),
    ]
    for i, solvent in enumerate(["甲醇", "乙醇", "丙酮", "乙腈", "二氯甲烷",
                                 "正己烷", "甲苯", "四氢呋喃", "乙酸乙酯", "异丙醇"], start=1):
        items.append((f"残留溶剂-{solvent}", "≤0.5%", f"{i * 0.037:.3f}", "%", "符合"))
    for i in range(1, 13):
        items.append((f"有关物质-单个杂质{chr(64 + i)}", "≤0.2%", f"{i * 0.011:.3f}", "%", "符合"))
    return items


# 一个样品一行数据，(检验项目, 标准规定, 检验结果, 单位, 单项结论)
SAMPLES = [
    ("S-2026-0912-001", "注射用头孢曲松钠", "00903", "张岚", "2026-09-08", [
        ("性状", "白色至类白色结晶性粉末", "白色结晶性粉末", "—", "符合"),
        ("含量", "95.0%~105.0%", "99.4", "%", "符合"),
        ("有关物质", "≤1.0%", "0.3", "%", "符合"),
        # 边界：结果还没出来，格子里是空的
        ("干燥失重", "≤8.0%", "", "%", "待检"),
    ]),
    # 边界：样品名称里带 &（水系统取样点常这么写）
    ("S-2026-0912-002", "注射用水（PW&WFI 系统 A 线取样点）", "260912", "王敏", "2026-09-09", [
        ("电导率", "≤1.3 μS/cm", "0.8", "μS/cm", "符合"),
        # 边界：结果里也带小于号
        ("微生物限度", "≤100 cfu/ml", "<100", "cfu/ml", "符合"),
    ]),
    # 边界：样品编号里带斜杠，直接当文件名写不出去
    ("S/2026/0912/003", "葡萄糖注射液（5%）", "00907", "李翔", "2026-09-09", [
        ("可见异物", "应符合规定", "符合", "—", "符合"),
        # 边界：标准规定以小于号开头
        ("细菌内毒素", "<0.5 EU/ml", "0.12", "EU/ml", "符合"),
        ("含量", "95.0%~105.0%", "0.4", "%", "不符合"),
    ]),
    # 边界：一个样品 22 个检项，一页装不下，要跨页
    ("S-2026-0912-004", "复方氨基酸注射液（18AA-Ⅱ）", "20260912", "张岚", "2026-09-10",
     _full_items()),
]


# ---------- 下半部分：写成 CSV ----------

def main():
    RAW.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for sample_id, name, batch, operator, date, items in SAMPLES:
        for item, spec, result, unit, verdict in items:
            rows.append([sample_id, name, batch, item, spec, result, unit, verdict, operator, date])
    # 表尾：空行 + 合计行 + 说明行，仪器导出的文件基本都带这些。
    # 合计行的条数会落到「检验项目」那一列（仪器出来的表就是这样错位的），
    # 光看样品编号和检验项目都不保险，脚本里再拿检测日期兜一道。
    rows.append([])
    rows.append(["合计", "", "", str(len(rows)), "", "", "", "", "", ""])
    rows.append(["说明：本表由仪器工作站直接导出，空白格表示尚未出结果。", "", "", "", "", "", "", "", "", ""])

    with open(RAW, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(HEAD)
        w.writerows(rows)
    print(f"已生成 {RAW.name}：{len(SAMPLES)} 个样品，{sum(len(s[5]) for s in SAMPLES)} 行明细")


if __name__ == "__main__":
    main()

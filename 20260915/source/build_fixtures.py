def write_recv() -> Path:
    """同一受试者同一类型会给多管，编号按 01/02 往下排。"""
    path = RAW / "样本接收明细_扫码枪导出.csv"
    seen: dict = {}
    rows = []
    for way, center, seq, visit, stype, taken, got, note in TUBES:
        subj = f"{center}{seq}"
        key = f"{subj}|{stype}"
        seen[key] = seen.get(key, 0) + 1
        code = TYPE_CODE.get(stype, "OTH")
        rows.append([way, f"{subj}-{code}{seen[key]:02d}", subj, center, CENTER_NAME[center],
                     visit, stype, taken, got, note])
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(RECV_HEAD)
        w.writerows(rows)
        w.writerow([])                                        # 表尾脏行，读的时候要丢掉
        w.writerow(["合计", "", "", "", "", "", "", "", "", str(len(rows))])
        w.writerow(["说明：由接收台扫码枪导出，未含运输温度", "", "", "", "", "", "", "", "", ""])
    return path



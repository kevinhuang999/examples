# -*- coding: utf-8 -*-
"""重造 20260916 示例的输入数据，写进包根的 01_raw_data/。

上半个文件：造方案规格与中心入组计划（一份方案、几个中心）
下半个文件：造物料批次台账（一个管型挂好几个批次）

数据故意留了边界：方案修订留下的重复行、仓库里没有对应规格的管型、
计划例数为 0 的中心、访视模板在方案里查不到的中心、库存不够的管型、
效期盖不到采样的批次、以及规格相近容易误领的干扰料（内旋冻存管、3.8% 凝血管）。
正常数据跑通不代表对，边界才是用来抓 bug 的。
用法：
    python source/build_fixtures.py
"""
import csv
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent      # 写回包根（这个脚本在 source/ 里）
RAW = BASE / "01_raw_data"

# ---------- 上半：方案规格 + 中心入组计划 ----------
SPEC_HEAD = ["访视模板", "访视编号", "访视点", "管型", "每例管数", "采血量mL", "处理要求"]
PLAN_HEAD = ["中心编号", "中心名称", "国家", "访视模板", "计划例数", "启动日期"]

# 方案规格：一行 = 某个模板里某个访视点要采的一种管，给的是「每例」用量。
# 真正的量 = 每例管数 × 该中心计划例数，脚本要算的就是这一下。
SPEC = [
    # 标准模板：筛选期 + 基线 + 随访，基线带 PK 冻存和凝血检查
    ("标准", "V1", "筛选期", "EDTA抗凝管", "1", "6.0", "室温转运"),
    ("标准", "V1", "筛选期", "促凝管", "1", "5.0", "室温转运"),
    ("标准", "V1", "筛选期", "尿杯", "1", "0", "室温转运"),
    ("标准", "V2", "基线", "EDTA抗凝管", "1", "6.0", "室温转运"),
    ("标准", "V2", "基线", "促凝管", "2", "5.0", "2~8℃转运"),
    ("标准", "V2", "基线", "冻存管", "2", "1.8", "离心后 -20℃ 冻存"),
    ("标准", "V2", "基线", "柠檬酸钠凝血管", "1", "3.2", "室温转运"),
    ("标准", "V2", "基线", "血沉管", "1", "1.6", "室温转运"),      # 物料表里没有这个规格
    ("标准", "V3", "随访D1", "EDTA抗凝管", "1", "6.0", "室温转运"),
    ("标准", "V3", "随访D1", "促凝管", "1", "5.0", "2~8℃转运"),

    # 减量模板：不参加 PK 采血的中心，基线只有 EDTA 和促凝管
    ("减量", "V1", "筛选期", "EDTA抗凝管", "1", "6.0", "室温转运"),
    ("减量", "V1", "筛选期", "促凝管", "1", "5.0", "室温转运"),
    ("减量", "V1", "筛选期", "尿杯", "1", "0", "室温转运"),
    ("减量", "V2", "基线", "EDTA抗凝管", "1", "6.0", "室温转运"),
    ("减量", "V2", "基线", "促凝管", "1", "5.0", "2~8℃转运"),
    ("减量", "V3", "随访D1", "EDTA抗凝管", "1", "6.0", "室温转运"),
    ("减量", "V3", "随访D1", "促凝管", "1", "5.0", "2~8℃转运"),

    # 方案修订留在文件里的旧行：基线促凝管以前是 1 支，改成 2 支后旧行没删
    ("标准", "V2", "基线", "促凝管", "1", "5.0", "2~8℃转运"),
]

# 中心入组计划：一个中心一行。例数是项目组给的，还没启动的中心写 0。
PLAN = [
    ("01001", "上海中心", "中国", "标准", "12", "2026-08-01"),
    ("01002", "北京中心", "中国", "减量", "8", "2026-08-15"),
    ("01003", "广州中心", "中国", "标准", "0", ""),            # 已建中心号，还没启动入组
    ("01004", "成都中心", "中国", "标准", "5", "2026-09-01"),
    ("01005", "首尔中心", "韩国", "减量", "3", "2026-09-10"),
    ("01006", "曼谷中心", "泰国", "加强", "4", "2026-09-12"),   # 这个模板方案里根本没有
]


def write_spec() -> Path:
    """文件尾部挂合计行和说明行——导出的文件都带，读的时候靠第一列空值丢掉。"""
    path = RAW / "研究规格_方案导出.csv"
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(SPEC_HEAD)
        w.writerows(SPEC)
        w.writerow([])
        w.writerow(["合计", "", "", "", str(len(SPEC)), "", ""])
        w.writerow(["说明：由方案规格文件导出，用量为每例用量，未含各中心例数", "", "", "", "", "", ""])
    return path


def write_plan() -> Path:
    path = RAW / "中心入组计划_项目组导出.csv"
    total = sum(int(r[4]) for r in PLAN)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(PLAN_HEAD)
        w.writerows(PLAN)
        w.writerow([])
        w.writerow(["", "合计", "", "", str(total), ""])
        w.writerow(["", "说明：例数由项目组每周五更新，未启动的中心写 0", "", "", "", ""])
    return path


# ---------- 下半：物料批次台账（仓库导出，一个管型挂好几个批次）----------
STOCK_HEAD = ["管型", "批次号", "效期", "库存支数"]

# 仓库按自己录的规格名记料，跟方案上写的用途名不一样，得脚本里显式对上。
# 故意混进两种「规格相近但不是一个东西」的干扰料：内旋 vs 外旋冻存管、3.2% vs 3.8% 凝血管。
STOCK = [
    ("紫帽 EDTA-K2 6mL", "B2302C", "2026-11-30", "60"),        # 效期盖不到采样窗口，不能排
    ("紫帽 EDTA-K2 6mL", "B2508A", "2027-08-31", "900"),
    ("黄帽 促凝 5mL", "B2301D", "2026-12-31", "40"),           # 同上，不能排
    ("黄帽 促凝 5mL", "B2509B", "2027-06-30", "60"),           # 效期近，FEFO 先出它
    ("黄帽 促凝 5mL", "B2601A", "2027-11-30", "400"),
    ("冻存管 2mL 外旋", "B2507E", "2028-03-31", "30"),         # 排到成都中心就不够了
    ("冻存管 2mL 内旋", "B2507J", "2028-03-31", "300"),        # 内旋，不能顶外旋
    ("尿杯 100mL 带盖", "B2506F", "2027-09-30", "120"),
    ("蓝帽 柠檬酸钠 3.2%", "B2505G", "2027-05-31", "200"),
    ("蓝帽 柠檬酸钠 3.8%", "B2505H", "2027-05-31", "150"),     # 3.8%，不能顶 3.2%
]


def write_stock() -> Path:
    path = RAW / "物料批次_仓库导出.csv"
    total = sum(int(r[3]) for r in STOCK)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(STOCK_HEAD)
        w.writerows(STOCK)
        w.writerow([])
        w.writerow(["", "合计", "", str(total)])
        w.writerow(["", "说明：库存为仓库台账数，未扣已被其他项目占用的部分", "", ""])
    return path


if __name__ == "__main__":
    RAW.mkdir(parents=True, exist_ok=True)
    print("方案规格：", write_spec().name, f"（{len(SPEC)} 行，其中 1 行是修订前的旧行）")
    print("入组计划：", write_plan().name, f"（{len(PLAN)} 个中心）")
    print("物料批次：", write_stock().name, f"（{len(STOCK)} 个批次）")

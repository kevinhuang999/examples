def report_file(report_no: str) -> str:
    """一份报告对应一个原件文件。真实场景是 PDF，示例用 .txt 占位。"""
    return report_no + ".txt"


def build_sources():
    """上半：建报告原件目录。缺的那份不放，另放一份索引里没有的。"""
    if SRC_DIR.exists():
        shutil.rmtree(SRC_DIR)
    SRC_DIR.mkdir(parents=True)
    for r in REPORTS:
        name = report_file(r[0])
        if name == MISSING_FILE:
            continue                                  # 索引里有、目录里没有
        (SRC_DIR / name).write_text(f"{r[0]}  {r[3]}  {r[4]}\n", encoding="utf-8")
    (SRC_DIR / EXTRA_FILE).write_text("上一批残留的报告\n", encoding="utf-8")
    print(f"报告原件目录 {SRC_DIR.name}/：{len(REPORTS) - 1 + 1} 个文件"
          f"（故意缺 1 份、故意多 1 份）")


def build_csv():
    """下半：写两份 CSV。索引带表尾的合计行与说明行，规则表也带一行。

    表尾那两行故意把文字放在「中心名称」列，首列留空 —— 系统导出的合计行就是这个样子，
    靠"报告编号非空"一行代码就能丢掉，不需要按关键字去认「合计」两个字。
    """
    with open(INDEX_FILE, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(INDEX_COLS)
        for r in REPORTS:
            w.writerow([r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7], report_file(r[0])])
        w.writerow(["", "", "", "", "", "", "", "", ""])                      # 表尾空行
        w.writerow(["", "", f"合计 {len(REPORTS)} 份", "", "", "", "", "", ""])
        w.writerow(["", "", "说明：报告日期为空的表示报告还没出，先挂着", "", "", "", "", "", ""])

    with open(RULE_FILE, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(RULE_COLS)
        for r in RULES:
            w.writerow(list(r))
    print(f"报告索引 {INDEX_FILE.name}：{len(REPORTS)} 份报告（含表尾合计与说明行）")
    print(f"中心分发规则 {RULE_FILE.name}：{len(RULES) - 1} 个中心（含表尾合计行）")


if __name__ == "__main__":
    RAW.mkdir(parents=True, exist_ok=True)
    build_sources()
    build_csv()
    print("输入数据已重建。")

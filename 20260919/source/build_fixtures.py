PANEL_ORDER = []
for _r in PANEL_ROWS:
    if _r[0] and _r[0] not in PANEL_ORDER:
        PANEL_ORDER.append(_r[0])


def write_csv(path: Path, header, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def build_panel():
    write_csv(TPL_DIR / "访视点检项清单.csv", ["访视点", "访视序号", "检项"], PANEL_ROWS)


def panel_items(visit: str):
    order = []
    for v, _, item in PANEL_ROWS:
        if v == visit and item not in order:
            order.append(item)
    return order


def build_results():
    header = ["受试者编号", "访视点", "采样日期", "检项", "结果", "单位", "参考下限", "参考上限"]
    rows = []
    for subj, visit, day, override, skipped, extra in VISITS:
        for item in panel_items(visit):
            if item in skipped:
                continue
            value, unit, low, high = ITEM_NORMAL[item]
            rows.append([subj, visit, day, item, override.get(item, value), unit, low, high])
        if extra:
            rows.append([subj, visit, day, extra[0], extra[1], extra[2], extra[3], extra[4]])
    rows += EXTRA_ROWS
    # 仪器导出的表尾：一条合计行 + 一条说明行。首列都留空，靠"编号非空"把它们丢掉。
    rows.append(["", "", "", "合计", str(len(rows)), "", "", ""])
    rows.append(["", "", "", "说明：结果为空表示本次未出结果，不是正常", "", "", "", ""])
    write_csv(RAW_DIR / "检验结果_仪器导出.csv", header, rows)



LEDGER_HEADER = ["样本编号", "中心编号", "研究方案", "检项类别", "采集时间",
                 "接收完成时间", "报告发出时间", "TAT时限(小时)", "起算口径", "计时方式"]
PAUSE_HEADER = ["样本编号", "暂停开始时间", "暂停结束时间", "暂停原因"]
CALENDAR_HEADER = ["日期", "是否工作日"]


def write_csv(path, header, rows, note):
    """写 CSV：utf-8-sig（Excel 双击不乱码），表尾加合计行与说明行。

    **合计与说明必须让第一列空着** —— 脚本认"第一列是不是空"来跳过表尾，
    合计数字写进第一列，就会被当成一条样本，凭空多出一条异常。
    """
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        for row in rows:
            w.writerow(list(row))
        w.writerow([""] + note + [""] * (len(header) - 1 - len(note)))


def main():
    RAW.mkdir(parents=True, exist_ok=True)
    cal = calendar_rows()
    write_csv(RAW / "工作日历.csv", CALENDAR_HEADER,
              [(r["日期"], r["是否工作日"]) for r in cal],
              ["说明：调休上班的周末标「是」，法定假日标「否」"])

    write_csv(RAW / "样本接收台账.csv", LEDGER_HEADER, LEDGER,
              [f"合计 {len(LEDGER)} 条",
               "说明：数据截止 2026-09-22 10:00，由接收登记系统导出，"
               "时间为空表示还没发生"])

    write_csv(RAW / "计时暂停记录.csv", PAUSE_HEADER, PAUSES,
              ["说明：一段一行；结束时间为空表示这段停表还没结束"])

    print(f"工作日历 {len(cal)} 天（工作日 {sum(1 for r in cal if r['是否工作日'] == '是')} 天）")
    print(f"样本接收台账 {len(LEDGER)} 条")
    print(f"计时暂停记录 {len(PAUSES)} 段，覆盖 {len({p[0] for p in PAUSES})} 个样本编号")
    print(f"输出目录：{RAW}")


if __name__ == "__main__":
    main()


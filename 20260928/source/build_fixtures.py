def build_template():
    TPL.mkdir(parents=True, exist_ok=True)
    wb = Workbook()
    wb.remove(wb.active)
    for name, head in TPL_SHEETS.items():
        ws = wb.create_sheet(name)
        ws.append(head)
        for i, _ in enumerate(head, 1):
            c = ws.cell(row=1, column=i)
            c.font = Font(name="微软雅黑", size=10, bold=True)
            c.fill = PatternFill("solid", start_color="DDEBF7")
            c.alignment = Alignment(horizontal="center")
            ws.column_dimensions[get_column_letter(i)].width = max(12, len(_) * 2 + 4)
        ws.freeze_panes = "A2"
    wb.save(TPL / "开票对账台账模板.xlsx")



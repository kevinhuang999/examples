def write_csv(path, header, rows, tail):
    lines = [",".join(header)]
    for r in rows:
        lines.append(",".join('"%s"' % str(x).replace('"', '""') for x in r))
    lines.append(tail)
    path.write_text("\r\n".join(lines) + "\r\n", encoding="utf-8-sig")



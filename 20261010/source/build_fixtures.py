# -*- coding: utf-8 -*-
"""造示例用的「仪器导出文件」与「样品对照表」——只跑一次，之后 run.py 直接读结果。

上半个文件建模板（样品对照表），下半个文件造仪器导出的结果文件。
故意塞了边界情况：文件名不带样品号、同一份文件里混着两个样品的峰、
样品号匹配不上对照表、同一个样品出现两条结果、结果值不是数字（ND / 未检出）。

跑法：
    python source/build_fixtures.py
"""
import csv
import socket
from datetime import datetime
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent   # 写回示例根目录
RAW = BASE / "01_raw_data"
TPL = BASE / "source" / "templates"


def build_sample_map():
    """样品对照表：把仪器软件吐出来的「进样瓶位 / 文件名标识」映射到实验室自己的样品号。

    它是业务资产，写在表里、不写死在代码里——仪器换了、编号规则改了，改表不改代码。
    """
    TPL.mkdir(parents=True, exist_ok=True)
    rows = [
        ["仪器标识", "实验室样品号", "检测项目", "备注"],
        ["V01-A1", "0000182", "含量测定", ""],
        ["V01-A2", "0000183", "含量测定", ""],
        ["V01-A3", "0000184", "含量测定", ""],
        ["V01-A4", "0000185", "含量测定", ""],
        ["V02-B1", "0000186", "有关物质", ""],
        ["V02-B2", "0000187", "有关物质", "复检"],
        ["V02-B3", "0000188", "有关物质", ""],
        ["V03-C1", "0000189", "含量测定", ""],
        ["V04-D1", "0000190", "含量测定", "老仪器：文件名带号"],
        # 故意留一个对照表里没有的仪器标识 V99-Z9，用来演示「匹配不上」怎么挂起
    ]
    p = TPL / "样品对照表.csv"
    with p.open("w", encoding="utf-8-sig", newline="") as f:
        csv.writer(f).writerows(rows)
    print("已生成模板：", p.name, f"（{len(rows) - 1} 条对照）")


def _write_csv(name, rows, encoding="utf-8-sig"):
    p = RAW / name
    with p.open("w", encoding=encoding, newline="") as f:
        csv.writer(f).writerows(rows)
    print("已生成仪器导出：", name, f"（{len(rows) - 1} 行结果）")


def build_instruments():
    """造 CDS（色谱工作站）导出的结果文件，故意覆盖各种真实边界。"""
    if RAW.exists():                       # 先把上次造的文件清掉，保证重跑结果一致
        for old in RAW.iterdir():
            if old.is_file():
                old.unlink()
    RAW.mkdir(parents=True, exist_ok=True)

    # ① 常规：文件名直接带实验室样品号（仪器命名规范的老仪器常这样）
    _write_csv("RESULT_0000190_20261010.csv", [
        ["组分", "保留时间", "峰面积", "含量(%)"],
        ["主成分", "3.215", "15234.5", "99.45"],
        ["杂质A", "5.870", "45.2", ""],
    ])

    # ② 关键边界：文件名只有时间戳（不带样品号），样品号要靠「进样瓶位」列反查
    _write_csv("CDS_20261010090215.csv", [
        ["样品名称", "进样瓶位", "组分", "含量(%)"],
        ["20261010-含量测定", "V01-A1", "主成分", "99.52"],
        ["20261010-含量测定", "V01-A2", "主成分", "98.71"],
    ])

    # ③ 关键边界：一份文件里混着两个不同样品（一次序列跑完一份汇总）
    _write_csv("CDS_SEQ_20261010_A.csv", [
        ["瓶位", "组分", "保留时间", "峰面积"],
        ["V01-A3", "主成分", "3.204", "15102.3"],
        ["V01-A3", "杂质B", "6.115", "8.4"],
        ["V01-A4", "主成分", "3.198", "14988.7"],
    ])

    # ④ 关键边界：样品号匹配不上对照表（V99-Z9 不在对照表里）
    _write_csv("CDS_20261010_unknown.csv", [
        ["瓶位", "组分", "峰面积"],
        ["V99-Z9", "主成分", "15001.0"],
    ])

    # ⑤ 关键边界：同一个样品出现两条结果（复检 / 平行样），值不一致
    _write_csv("CDS_20261010_recheck.csv", [
        ["进样瓶位", "检测项目", "结果", "单位"],
        ["V02-B2", "有关物质", "0.31", "%"],
        ["V02-B2", "有关物质", "0.29", "%"],
    ])

    # ⑥ 关键边界：结果值不是纯数字（未检出 / ND / 带小于号）
    _write_csv("CDS_20261010_qualitative.csv", [
        ["进样瓶位", "组分", "结果", "单位"],
        ["V02-B1", "杂质C", "未检出", ""],
        ["V02-B3", "杂质C", "ND", ""],
        ["V03-C1", "杂质C", "<0.05", "%"],
    ])

    # ⑦ 说明文件：不是数据，不该被当结果读
    (RAW / "仪器导出说明_20261010.txt").write_text(
        "色谱工作站（CDS）导出说明\n"
        "1）本批导出 6 个结果文件，命名规则不一，有的带样品号、有的只有时间戳；\n"
        "2）样品号可能在文件名里，也可能在「进样瓶位」列里，需按对照表映射；\n"
        "3）结果列可能出现 未检出 / ND / <0.05 之类非数值写法，原样保留不要当 0；\n"
        "4）本文件仅作说明，不参与解析。\n",
        encoding="utf-8",
    )
    print("已生成仪器导出：仪器导出说明_20261010.txt")


if __name__ == "__main__":
    name = socket.gethostname()
    print(f"运行主机：{name}   生成时间：{datetime.now():%Y-%m-%d %H:%M:%S}")
    build_sample_map()
    build_instruments()
    print("\n完成。接下来跑：python run.py")

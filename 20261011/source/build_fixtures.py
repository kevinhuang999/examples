def write_specs():
    TPL.mkdir(parents=True, exist_ok=True)
    out = TPL / "规格限度表.csv"
    with out.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["检测项目", "判定方式", "下限", "上限", "单位"])
        w.writerows(SPECS)
    return out


def write_details():
    RAW.mkdir(parents=True, exist_ok=True)
    out = RAW / "检测结果明细.csv"
    with out.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)

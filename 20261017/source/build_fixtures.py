import csv
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment

BASE_DIR = Path(__file__).resolve().parent.parent
RAW_DIR = BASE_DIR / "01_raw_data"

HEAD_FONT = Font(bold=True)
HEAD_FILL = PatternFill("solid", fgColor="DCE6F1")


def style_sheet(ws, widths):
    for cell in ws[1]:
        cell.font = HEAD_FONT
        cell.fill = HEAD_FILL
        cell.alignment = Alignment(horizontal="center")
    for idx, width in enumerate(widths, start=1):
        ws.column_dimensions[ws.cell(row=1, column=idx).column_letter].width = width
    ws.freeze_panes = "A2"


def build_plan():
    """方案表：一个批号 + 一个考察条件 = 一条考察线，各自有起始日和计划时间点。"""
    wb = Workbook()
    ws = wb.active
    ws.title = "考察方案"
    ws.append(["批号", "考察条件", "考察起始日", "计划时间点（月）", "规格"])
    rows = [
        ("0201", "加速 40℃/75%RH", "2024-08-05", "0,1,2,3,6", "片剂 0.5g"),
        ("0202", "加速 40℃/75%RH", "2024-08-05", "0,1,2,3,6", "片剂 0.5g"),
        ("0201", "长期 25℃/60%RH", "2024-08-05", "0,3,6,9", "片剂 0.5g"),
        ("0202", "长期 25℃/60%RH", "2024-08-05", "0,3,6,9", "片剂 0.5g"),
    ]
    for row in rows:
        ws.append(list(row))
    for cell in ws["A"][1:]:
        cell.number_format = "@"          # 批号带前导零，必须存成文本
    style_sheet(ws, [8, 20, 14, 18, 12])
    wb.save(RAW_DIR / "稳定性考察方案.xlsx")


def build_spec():
    """质量标准：上下限留空表示这一侧不限。"""
    wb = Workbook()
    ws = wb.active
    ws.title = "质量标准"
    ws.append(["检项", "单位", "下限", "上限"])
    rows = [
        ("含量", "%", 95.0, 105.0),
        ("有关物质总杂", "%", None, 1.0),
        ("pH", "", 4.5, 6.5),
        ("水分", "%", None, 5.0),
    ]
    for row in rows:
        ws.append(list(row))
    style_sheet(ws, [16, 8, 8, 8])
    wb.save(RAW_DIR / "质量标准.xlsx")


